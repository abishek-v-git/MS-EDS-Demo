import datetime as dt

from django.conf import settings
from django.db import models
from django.db.models import Max


def eds_code(prefix, seq):
    """("EDS", 1) -> "EDS-000001"; the digit count is settings.EDS_ID_DIGITS."""
    return f"{prefix}-{seq:0{settings.EDS_ID_DIGITS}d}"


class EDSRecord(models.Model):
    """Root EDS record. One row per EDS Record ID; every other topic hangs off this.

    Rows from the Excel input are matched on Demand-line ID. Fields listed in
    AUTO_FIELDS are generated by the system and are not accepted from the input file:

        EDS Record ID           EDS-000001   sequential, set once on create
        Current gate            "Demand Signal Intake"
        Record owner and backup "EDS Admin / Unassigned"
        Created date            the day the record was created (never changes)
        Refreshed date          the last day an import or edit changed the record
        Review date             Refreshed date + EDS_REVIEW_INTERVAL_DAYS

    Prefixes, defaults and the review interval are set in settings (EDS_*).
    """

    AUTO_FIELDS = ("eds_record_id", "current_gate", "record_owner_backup",
                   "created_date", "refreshed_date", "review_date")

    # Long / combined text: shown as an expandable box in the table
    EXPANDABLE_FIELDS = (
        "source_signal",
        "version_change_reason",
    )

    seq = models.PositiveIntegerField(unique=True, editable=False)
    eds_record_id = models.CharField("EDS Record ID", max_length=100, unique=True, editable=False)
    program = models.TextField("Program ID/name", blank=True, default="")
    program_phase = models.TextField("Program phase", blank=True, default="")
    demand_line_id = models.CharField("Demand-line ID", max_length=100, blank=True, default="", db_index=True)
    parent_eds_id = models.TextField("Parent EDS ID", blank=True, default="")
    current_gate = models.TextField(editable=False, verbose_name="Current gate", blank=True, default="")
    record_owner_backup = models.TextField(editable=False, verbose_name="Record owner and backup", blank=True, default="")
    created_date = models.TextField(editable=False, verbose_name="Created date", blank=True, default="")
    refreshed_date = models.TextField(editable=False, verbose_name="Refreshed date", blank=True, default="")
    review_date = models.TextField(editable=False, verbose_name="Review date", blank=True, default="")
    source_signal = models.TextField("Source signal", blank=True, default="")
    version_change_reason = models.TextField("Version and change reason", blank=True, default="")

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["seq"]
        verbose_name = "EDS record"

    def __str__(self):
        return self.eds_record_id

    # ── generated fields ──────────────────────────────────────────────────────

    @classmethod
    def next_seq(cls):
        return (cls.objects.aggregate(m=Max("seq"))["m"] or 0) + 1

    @classmethod
    def generated_fields(cls, seq):
        """Identity values for a new record with sequence number `seq`."""
        return {
            "seq": seq,
            "eds_record_id": eds_code(settings.EDS_ID_PREFIX, seq),
            "current_gate": settings.EDS_DEFAULT_GATE,
            "record_owner_backup": f"{settings.EDS_RECORD_OWNER} / {settings.EDS_RECORD_BACKUP}",
        }

    @staticmethod
    def lifecycle_dates(created: dt.date, refreshed: dt.date):
        """-> {"created_date", "refreshed_date", "review_date"} as YYYY-MM-DD strings."""
        review = refreshed + dt.timedelta(days=settings.EDS_REVIEW_INTERVAL_DAYS)
        return {"created_date": created.isoformat(), "refreshed_date": refreshed.isoformat(),
                "review_date": review.isoformat()}
