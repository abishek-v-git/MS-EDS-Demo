"""Topic registry.

Every installed app whose AppConfig defines ``topic_order`` is a topic. Its model's
fields (in declaration order) are the topic's Excel columns, and each field's
``verbose_name`` is the exact Excel header.
"""
from dataclasses import dataclass
from functools import cache

from django.apps import apps
from django.urls import reverse

IDENTITY_APP = "record_identity"
# Shown as frozen context columns at the start of every topic table.
CONTEXT_FIELDS = ("program", "eds_record_id")
SYSTEM_FIELDS = {"id", "seq", "record", "created_at", "updated_at"}


@dataclass(frozen=True)
class Topic:
    label: str
    title: str
    slug: str
    icon: str
    accent: str
    model: type
    order: int
    group: str = ""

    @property
    def is_identity(self):
        return self.label == IDENTITY_APP

    @property
    def fields(self):
        """[(field_name, excel_header), ...] in column order."""
        return [
            (f.name, str(f.verbose_name))
            for f in self.model._meta.concrete_fields
            if f.name not in SYSTEM_FIELDS
        ]

    @property
    def auto_fields(self):
        """Field names generated by the system (never read from the input file)."""
        return set(getattr(self.model, "AUTO_FIELDS", ()))

    @property
    def expandable_fields(self):
        """Long-text fields rendered as click-to-expand boxes."""
        return set(getattr(self.model, "EXPANDABLE_FIELDS", ()))

    @property
    def date_fields(self):
        """Fields that must hold a date (stored as YYYY-MM-DD)."""
        return set(getattr(self.model, "DATE_FIELDS", ()))

    @property
    def number_fields(self):
        """Fields that must hold a number (stored like "1234" / "12.5")."""
        return set(getattr(self.model, "NUMBER_FIELDS", ()))

    @property
    def monthly_field(self):
        return getattr(self.model, "MONTHLY_PROFILE_FIELD", None)

    @property
    def monthly_triggers(self):
        return set(getattr(self.model, "MONTHLY_PROFILE_TRIGGERS", ()))

    @property
    def input_fields(self):
        """[(field_name, excel_header), ...] expected in the input file."""
        auto = self.auto_fields
        return [(n, h) for n, h in self.fields if n not in auto]

    @property
    def url(self):
        return reverse(f"{self.label}:table")

    @property
    def data_url(self):
        return reverse(f"{self.label}:data")


@cache
def get_topics():
    topics = []
    for cfg in apps.get_app_configs():
        if not hasattr(cfg, "topic_order"):
            continue
        topics.append(Topic(
            label=cfg.label,
            title=cfg.verbose_name,
            slug=cfg.topic_slug,
            icon=cfg.topic_icon,
            accent=cfg.topic_accent,
            model=cfg.get_model(cfg.topic_model),
            order=cfg.topic_order,
            group=getattr(cfg, "topic_group", ""),
        ))
    return tuple(sorted(topics, key=lambda t: t.order))


@cache
def get_groups():
    """Consecutive topics sharing a group -> [(group_name, (topic, ...)), ...]; "" = standalone."""
    groups = []
    for t in get_topics():
        if groups and t.group and groups[-1][0] == t.group:
            groups[-1][1].append(t)
        else:
            groups.append((t.group, [t]))
    return tuple((name, tuple(ts)) for name, ts in groups)


def get_topic(label):
    for t in get_topics():
        if t.label == label:
            return t
    raise LookupError(label)


def identity_model():
    return get_topic(IDENTITY_APP).model
